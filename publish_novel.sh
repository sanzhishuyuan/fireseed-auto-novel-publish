#!/bin/bash

# 小说ID
NOVEL_ID="huozhong-renjian-qilu"
SERVER_IP="43.128.134.77"
SSH_KEY="C:/Users/Administrator/.ssh/fireseed_key"
PROJECT_PATH="/root/ai-novel-lite"

echo "正在发布小说《火种之人间歧路》到服务器..."

# 创建小说目录
ssh -i "$SSH_KEY" root@$SERVER_IP << EOF
  # 创建目录结构
  mkdir -p $PROJECT_PATH/content/novels/$NOVEL_ID/{chapters,branches}
  
  # 创建meta.md
  cat > $PROJECT_PATH/content/novels/$NOVEL_ID/meta.md << 'METAEOF'
---
title: 火种之人间歧路
author: AI创作（全民共创）
description: 这是一本全民参与的现实向共创小说，以高中毕业、志愿择校为故事原点。每一次微小的选择偏差，都会衍生出完全不同的人生轨迹。人生没有标准答案，没有最优解，每一次选择，都是专属自己的人间归途。
status: ongoing
tags: 现实,青春,成长,抉择,人生
created_at: 2026-04-28
---

METAEOF

  echo "小说目录和meta文件创建完成"
EOF

# 上传第一章
ssh -i "$SSH_KEY" root@$SERVER_IP "cat > $PROJECT_PATH/content/novels/$NOVEL_ID/chapters/1-qilu.md" << 'CHAPTEREOF'
---
title: 第一章 歧路
book: 火种之人间歧路
order: 1
branch: main
choices:
  - text: "选择复读，明年再战"
    branch: "retry"
  - text: "接受二本，开始大学生活"
    branch: "college"
---

网吧的空调坏了。

李然坐在最角落的位置，屏幕的荧光照在她脸上，一动不动。

**515分。**

不多不少，刚好卡在本科线和专科线之间。

她盯着那串数字，看了三分钟。鼠标滚轮上上下下，分数线像两条平行线，把她的命运死死夹在中间。

"李然。"

有人拍她肩膀。

她没回头。知道是谁。

班主任站在她身后，手里夹着半根没点着的烟——网吧禁烟，他捏着烟就像捏着一根粉笔。

"看见了吧？"他声音很低，像怕吵醒什么。

"看见了。"

"怎么想？"

李然没说话。窗外知了叫得撕心裂肺，2008年的夏天热得让人喘不过气。

班主任拉开旁边的椅子坐下，椅子腿刮过地面，发出刺耳的声响。

"二本稳妥。"他说，"你报二本，我保证你能走。"

"我妈想让我冲一本。"

"冲？"班主任笑了，笑声干涩，"冲什么冲？差两分，两分就是天堑。"

李然转过头看他。

班主任四十多岁，头发已经半白。他教了二十年毕业班，见过太多这样的学生——卡在分数线上的，就像卡在悬崖边，往前一步是深渊，退后一步是平庸。

"人生没有重来。"他说，"选错了，就得认。"

"那要是选对了呢？"

"选对？"班主任又笑了，"哪有对错？只有结果。"

他站起身，拍了拍她的肩膀："晚上八点前交志愿单。我等你。"

他走了。脚步声消失在网吧的喧嚣里。

李然重新看向屏幕。

515分。就像一把锁，锁死了她所有的可能。

---

手机响了。

是她妈。

"喂？"

"然然啊，分数出来了吗？"电话那头的声音急切，背景里还有炒菜的声音。

"出来了。"

"多少？"

"515。"

短暂的沉默。

"那……那能上一本吗？"

"差两分。"

"两分啊……"她妈的声音里透出失望，但很快又打起精神，"没关系，我们报一本！万一今年分数线降了呢？"

"不会降的。"

"怎么不会？万一呢？就报一本，冲一冲！"

李然没说话。

"你爸也这么说。"她妈继续道，"咱们家这么多年，就你一个大学生，要上就上好的。二本算什么？出来找不到工作的。"

"二本也是本科。"

"那不一样！"她妈声音抬高，"你表姐去年二本毕业，现在还在家待业呢。听妈的，报一本。"

电话挂了。

李然把手机扔在桌上，屏幕亮了一下，又暗下去。

她想起班主任刚才说的话。

**人生没有重来。**

**选错了，就得认。**

可怎么选才算对？

她不知道。

---

志愿单摊在键盘旁边，白色的纸张被灯光照得发黄。

李然拿起笔。

笔尖悬在纸上，像一把悬在空中的刀。

第一志愿：**一本，不服从调剂。**

第二志愿：**二本，服从调剂。**

第三志愿：**二本，不服从调剂。**

她写得很慢，每个字都像是刻上去的。

写完最后一笔，她放下笔，长长吐出一口气。

手心里全是汗。

---

老板走过来，敲了敲她的桌子："同学，要关门了。"

李然抬头，才发现网吧里已经空无一人。

"几点了？"

"七点五十。"

还有十分钟。

她拿起志愿单，折好，放进书包最里层的夹层。

站起身时，腿有点麻。

走出网吧，夏夜的风扑面而来，带着燥热和尘土的气息。

街灯一盏盏亮起，照亮空荡荡的街道。

李然站在路边，看着手里的手机。

屏幕上显示着班主任的号码。

她按下拨号键。

"喂？"

"老师，我填好了。"

"报的什么？"

"一本。"

电话那头沉默了几秒。

"不服从调剂？"

"嗯。"

班主任叹了口气："李然，你想好了？"

"想好了。"

"好。"他说，"那祝你……好运。"

电话挂断。

李然把手机塞回口袋，抬头看向夜空。

2008年的夏天，星星很少。

但她看见了一颗，很亮，挂在城市边缘的天际线上。

她看了很久，直到那颗星被云层遮住。

然后她转身，走向回家的路。
CHAPTEREOF

echo "第一章上传完成"

# 在数据库中插入小说记录
